# Stamps the firmware with its version, for the panel and the GitHub updater
# (src/Updater.cpp), which compares it against the latest release's tag.
#
#   FW_VERSION set in the environment - used as-is. The release workflow
#     (.github/workflows/release.yml) sets it to the pushed tag, "v1.4.0".
#   otherwise - `git describe --tags --always --dirty`, so a local build reads
#     "v1.4.0-3-gabc1234-dirty" (or a bare hash before the first tag) and is
#     recognisable as a development build rather than a release.
#
# Written to a generated src/BuildVersion.cpp (gitignored) rather than passed
# as a -D define: a define changes the command line of every translation unit,
# so each new commit would rebuild the whole firmware; this way only one small
# file recompiles, and only when the version actually changed.

import os
import subprocess

Import("env")


def describe():
    version = os.environ.get("FW_VERSION", "").strip()
    if version:
        return version
    try:
        return subprocess.check_output(
            ["git", "describe", "--tags", "--always", "--dirty"],
            cwd=env["PROJECT_DIR"], stderr=subprocess.DEVNULL).decode().strip()
    except Exception:
        return "dev"


def write_version():
    version = describe().replace("\\", "").replace('"', "")[:31]
    path = os.path.join(env["PROJECT_DIR"], "src", "BuildVersion.cpp")
    content = (
        "// Generated by tools/version.py - do not edit, not committed.\n"
        "#include \"BuildVersion.h\"\n"
        "const char* const kFirmwareVersion = \"%s\";\n" % version)
    try:
        with open(path, "r") as f:
            if f.read() == content:
                return
    except OSError:
        pass
    with open(path, "w") as f:
        f.write(content)
    print("version: %s" % version)


write_version()
